#!/usr/bin/env python3
"""Generate docs/SOFTWARE_SPEC.md and godot/data/software.json from tools/specs/software_data.py.

    python tools/specs/gen_software.py [--root DIR]

Pure standard library and deterministic (no timestamps).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import software_data as sd  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
VERSION = "1.0"


def software_json():
    apps = []
    for a in sd.APPS:
        apps.append({"id": a["id"], "title": a["title"], "version": VERSION, "category": a["category"], "description": a["purpose"],
                     "screen_textures": list(a["textures"]), "categories": list(a["hosts"]), "rooms": list(a["rooms"]),
                     "hosts": list(a["hosts"]), "update_rate": a["rate"]})
    return {"version": 1, "fallback": "computer", "theme": sd.THEME,
            "categories": [{"id": i, "title": t} for i, t in sd.CATEGORIES],
            "apps": apps,
            "texture_map": dict(sorted(sd.TEXTURE_MAP.items())),
            "texture_prefix_map": dict(sorted(sd.TEXTURE_PREFIX_MAP.items())),
            "category_map": dict(sorted(sd.CATEGORY_APP.items()))}


def bullets(w, items):
    for i in items:
        w("* %s" % i)
    w("")


def app_section(w, n, a):
    w("### 4.%d `%s` - %s" % (n, a["id"], a["title"]))
    w("")
    w("**Category** %s | **Version** %s | **Update rate** %s" % (a["category"], VERSION, a["rate"]))
    w("")
    w("**Purpose.** %s" % a["purpose"])
    w("")
    w("**Who uses it.** %s" % a["users"])
    w("")
    w("**Hosted by.** Rooms (hints, the ids may change with the layout): %s. Machine categories: %s. Screen textures that open it: %s." % (
        ", ".join("`%s`" % r for r in a["rooms"]), ", ".join("`%s`" % h for h in a["hosts"]),
        ", ".join("`%s`" % t for t in a["textures"]) if a["textures"] else "none of its own (opened by category / prefix rules, see 3.2)"))
    w("")
    w("**Layout (1280x720 logical, wireframe)**")
    w("")
    w("```text")
    w(a["wireframe"])
    w("```")
    w("")
    w("**Widgets**")
    w("")
    bullets(w, a["widgets"])
    w("**Data sources**")
    w("")
    bullets(w, a["data"])
    w("**Interactions and keys** (plus the common keys of section 2)")
    w("")
    bullets(w, a["interactions"])
    w("**Alarms and error states**")
    w("")
    bullets(w, a["alarms"])
    w("**Effects on the game world** (through the shared `ShipState`)")
    w("")
    bullets(w, a["effects"])
    w("**Performance budget.** %s Update rate: %s Only the open app runs; the screen texture of the machine stays static while an app is open elsewhere." % (a["perf"], a["rate"]))
    w("")
    w("**Accessibility.** Every colour state also has a text or shape cue (OK / WARN / CRIT chips with icons); all actions are reachable with the keyboard; text is at least 18 px at 1280x720; `Settings.reduce_motion` stops sweeps and blinking; sounds have on-screen text equivalents.")
    w("")
    for title, items in a["extra"]:
        w("**%s**" % title)
        w("")
        bullets(w, items)
    w("**Acceptance tests**")
    w("")
    for i, t in enumerate(a["accept"], 1):
        w("%d. %s" % (i, t))
    w("")


