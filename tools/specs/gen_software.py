def write_all(root):
    md = generate()
    p = os.path.join(root, "docs", "SOFTWARE_SPEC.md")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(md)
    jp = os.path.join(root, "godot", "data", "software.json")
    with open(jp, "w") as f:
        json.dump(software_json(), f, indent=1, sort_keys=False)
        f.write("\n")
    return p, jp


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=ROOT)
    a = ap.parse_args()
    p, jp = write_all(a.root)
    print("wrote", os.path.relpath(p, a.root), os.path.relpath(jp, a.root))


if __name__ == "__main__":
    main()
